# ==========================
with tab1:
    col1, col2 = st.columns([1, 2])
    
    # --- GET USERS FROM ENV ---
    authorized_users = get_authorized_users()

    with col1:
        st.subheader("Configuration")
        
        # 1. USER VALIDATION
        tutor_name_input = st.text_input("Tutor Username")
        
        # Check Access
        is_authorized = False
        remaining_balance = 0
        
        if tutor_name_input:
            if tutor_name_input in authorized_users:
                is_authorized = True
                max_limit = authorized_users[tutor_name_input]
                
                # Fetch Usage from DB
                try:
                    current_usage = db_utils.get_tutor_usage(tutor_name_input)
                except:
                    current_usage = 0 # Default if DB fail
                
                remaining_balance = max_limit - current_usage
                usage_percent = min(current_usage / max_limit, 1.0)
                
                # Display Usage Meter
                st.write(f"**Credit Usage:** {current_usage:,} / {max_limit:,} Tokens")
                st.progress(usage_percent)
                
                if current_usage >= max_limit:
                    st.error("❌ Quota Exceeded. Contact Admin.")
                    is_authorized = False # Block access
                elif usage_percent > 0.9:
                    st.warning("⚠️ Low Balance")
                else:
                    st.success("✅ Active Plan")
            else:
                st.error("🚫 User not found in system.")

        uploaded_scheme = st.file_uploader("1. Marking Scheme (PDF)", type=["pdf"])
        
        st.write("**Exam Settings:**")
        max_score_input = st.number_input("Total Marks (0 = Auto-detect)", min_value=0, value=0)
        st.markdown("---")
        use_custom = st.checkbox("Use Custom Template?")
        uploaded_template = None
        if use_custom:
            uploaded_template = st.file_uploader("2. Report Template (PDF)", type=["pdf"])
    
    with col2:
        st.subheader("Student Uploads")
        uploaded_files = st.file_uploader("Drop student PDFs here", accept_multiple_files=True, type=["pdf"])

        # BUTTON LOGIC: Only active if Authorized AND has Files
        if st.button("Run Batch Grading", type="primary", disabled=(not is_authorized)):
            if not is_authorized:
                st.error("You are not authorized to grade.")
            elif not uploaded_files or not uploaded_scheme:
                st.error("Please upload the Marking Scheme and Student Papers.")
            else:
                st.info("Processing... please wait.")
                
                with open("temp_scheme.pdf", "wb") as f:
                    f.write(uploaded_scheme.getbuffer())
                
                template_path = None
                if uploaded_template:
                    with open("temp_template.pdf", "wb") as f:
                        f.write(uploaded_template.getbuffer())
                    template_path = "temp_template.pdf"
                
                progress_bar = st.progress(0)
                
                for i, student_file in enumerate(uploaded_files):
                    with open("temp_student.pdf", "wb") as f:
                        f.write(student_file.getbuffer())
                    
                    try:
                        score, feedback, tokens = grader_engine.grade_submission(
                            "temp_student.pdf", 
                            "temp_scheme.pdf", 
                            template_path,
                            max_score_override=max_score_input
                        )
                        
                        pdf_path = create_pdf_report(feedback, student_file.name)
                        student_url = storage_utils.upload_file(student_file, student_file.name)
                        
                        db_utils.save_grade(tutor_name_input, student_file.name, score, feedback, student_url, tokens)
                        
                        st.success(f"✅ {student_file.name} | Score: {score} | Tokens: {tokens}")
                        
                        with open(pdf_path, "rb") as pdf_file:
                            st.download_button(f"Download Report ({student_file.name})", pdf_file, file_name=pdf_path)
                            
                    except Exception as e:
                        st.error(f"Failed {student_file.name}: {e}")
                    
                    progress_bar.progress((i+1)/len(uploaded_files))

