# --- HELPER: USER AUTH & QUOTA ---
def get_authorized_users():
    """Parses the .env string 'user:limit,user2:limit' into a dict."""
    raw_string = os.environ.get("TUTOR_QUOTAS", "")
    users = {}
    if raw_string:
        for entry in raw_string.split(","):
            if ":" in entry:
                name, limit = entry.split(":")
                users[name.strip()] = int(limit.strip())
    return users

# --- PDF GENERATOR ---
class AestheticReport(FPDF):
    def header(self):
        self.set_fill_color(44, 62, 80)
        self.rect(0, 0, 210, 25, 'F')
        self.set_y(10)
        self.set_font('Arial', 'B', 16)
        self.set_text_color(255, 255, 255)
        self.cell(0, 10, 'Eskwela Grading Report', 0, 0, 'C')
        self.ln(25)

    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Generated by AI - Page {self.page_no()}', 0, 0, 'C')

def create_pdf_report(feedback_text, student_filename):
    pdf = AestheticReport()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    
    safe_text = feedback_text.encode('latin-1', 'replace').decode('latin-1')
    lines = safe_text.split('\n')
    
    for line in lines:
        line = line.strip()
        if not line:
            pdf.ln(2)
            continue
        if line.startswith("# "):
            pdf.ln(5)
            pdf.set_font("Arial", "B", 16)
            pdf.set_text_color(44, 62, 80)
            pdf.cell(0, 10, line.replace("# ", "").upper(), 0, 1, 'L')
            pdf.set_draw_color(200, 200, 200)
            pdf.line(10, pdf.get_y(), 200, pdf.get_y())
            pdf.ln(2)
        elif line.startswith("## "):
            pdf.ln(4)
            pdf.set_font("Arial", "B", 13)
            pdf.set_text_color(52, 152, 219)
            pdf.cell(0, 8, line.replace("## ", ""), 0, 1, 'L')
        elif line.startswith("**Q") or line.startswith("Q"):
            pdf.ln(3)
            pdf.set_font("Arial", "B", 11)
            pdf.set_text_color(0, 0, 0)
            pdf.cell(0, 6, line.replace("*", ""), 0, 1, 'L')
        elif "Status:" in line:
            pdf.set_font("Arial", "B", 10)
            if "Correct" in line: pdf.set_text_color(39, 174, 96)
            elif "Incorrect" in line: pdf.set_text_color(192, 57, 43)
            elif "Partial" in line: pdf.set_text_color(211, 84, 0)
            elif "UNATTEMPTED" in line: pdf.set_text_color(127, 140, 141)
            else: pdf.set_text_color(0, 0, 0)
            pdf.cell(0, 6, line.replace("*", ""), 0, 1, 'L')
        elif "Score:" in line:
            pdf.set_font("Arial", "B", 10)
            pdf.set_text_color(44, 62, 80)
            pdf.cell(0, 6, line.replace("*", ""), 0, 1, 'L')
        else:
            pdf.set_font("Arial", "", 10)
            pdf.set_text_color(50, 50, 50)
            pdf.multi_cell(0, 6, line.replace("*", ""))
            
    report_filename = f"Report_{student_filename}.pdf"
    pdf.output(report_filename)
    return report_filename

